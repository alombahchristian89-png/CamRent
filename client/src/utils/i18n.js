const reversePhraseDictionary = Object.entries(phraseDictionary).reduce((acc, [englishText, frenchText]) => {
  acc[frenchText] = englishText
  return acc
}, {})

const phraseFragments = {
  enToFr: [
    ['Welcome back', 'Bon retour'],
    ['Manage your properties and connect with tenants', 'Gerez vos proprietes et connectez-vous avec les locataires'],
    ['Recent Properties', 'Proprietes recentes'],
    ['Recent Inquiries', 'Demandes recentes'],
    ['Total Listings', 'Total des annonces'],
    ['Active Listings', 'Annonces actives'],
    ['Total Views', 'Vues totales'],
    ['Total Inquiries', 'Total des demandes'],
    ['View All', 'Voir tout']
  ]
}

phraseFragments.frToEn = phraseFragments.enToFr.map(([enValue, frValue]) => [frValue, enValue])

const replaceTrimmedValue = (rawValue, translatedValue) => {
  const trimmedValue = rawValue.trim()
  if (!trimmedValue) return rawValue
  return rawValue.replace(trimmedValue, translatedValue)
}

const getTargetMap = (language) => (language === 'fr' ? phraseDictionary : reversePhraseDictionary)

const translateTrimmedValue = (rawValue, language) => {
  const originalValue = String(rawValue || '')
  const trimmedValue = originalValue.trim()
  if (!trimmedValue) return null

  const targetMap = getTargetMap(language)
  const translatedValue = targetMap[trimmedValue]
  if (translatedValue && translatedValue !== trimmedValue) {
    return replaceTrimmedValue(originalValue, translatedValue)
  }

  const fragments = language === 'fr' ? phraseFragments.enToFr : phraseFragments.frToEn
  let nextValue = originalValue
  let hasFragmentReplacement = false

  fragments.forEach(([sourceText, targetText]) => {
    if (!sourceText || !targetText) return
    if (!nextValue.includes(sourceText)) return
    nextValue = nextValue.split(sourceText).join(targetText)
    hasFragmentReplacement = true
  })

  return hasFragmentReplacement ? nextValue : null
}

const translateTextNode = (node, language) => {
  if (!node || typeof node.nodeValue !== 'string') return
  const nextValue = translateTrimmedValue(node.nodeValue, language)
  if (!nextValue) return

  node.nodeValue = nextValue
}

const translatableAttributes = ['placeholder', 'title', 'aria-label', 'value']

const translateElementAttributes = (element, language) => {
  if (!element || typeof element.getAttribute !== 'function') return

  translatableAttributes.forEach((attributeName) => {
    const rawValue = element.getAttribute(attributeName)
    if (!rawValue) return

    const nextValue = translateTrimmedValue(rawValue, language)
    if (!nextValue || nextValue === rawValue) return

    element.setAttribute(attributeName, nextValue)
  })
}

export const translateDocumentText = (rootNode, language) => {
  if (!rootNode || typeof window === 'undefined') return

  const targetLanguage = language === 'fr' ? 'fr' : 'en'

  const walker = window.document.createTreeWalker(rootNode, NodeFilter.SHOW_TEXT)
  let currentNode = walker.nextNode()

  while (currentNode) {
    const parentTag = currentNode.parentElement?.tagName
    if (parentTag !== 'SCRIPT' && parentTag !== 'STYLE' && parentTag !== 'TEXTAREA') {
      translateTextNode(currentNode, targetLanguage)
    }
    currentNode = walker.nextNode()
  }

  if (rootNode.nodeType === Node.ELEMENT_NODE) {
    translateElementAttributes(rootNode, targetLanguage)
    rootNode.querySelectorAll('*').forEach((element) => {
      translateElementAttributes(element, targetLanguage)
    })
  }
}

export const translate = (language, key, fallback = '') => {
  const dictionary = translations[language] || translations.en
  if (dictionary[key]) return dictionary[key]
  if (translations.en[key]) return translations.en[key]
  return fallback || key
}
